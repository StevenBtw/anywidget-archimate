// Bundle the widget's TypeScript front end (src/anywidget_archimate/ui/index.ts and the modules it imports)
// into the one ES module the widget loads: src/anywidget_archimate/ui/dist/widget.js. Run after `npm ci` in
// the package root: npm run build. With --check it builds in memory and fails when the committed file differs
// (CI, and tests/test_ui.py).
import { build } from "esbuild";

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

import { dirname, join } from "node:path";

import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));

const ui = join(here, "..", "src", "anywidget_archimate", "ui");

const out = join(ui, "dist", "widget.js");

const result = await build({
  entryPoints: [join(ui, "index.ts")],
  // Inputs are named relative to this folder in the output's comments: the same file from wherever the script runs
  absWorkingDir: ui,
  bundle: true,
  format: "esm",
  // Readable output: a stack trace in a notebook points at code a person can follow
  minify: false,
  target: "es2022",
  charset: "utf8",
  legalComments: "none",
  write: false,
  logLevel: "warning",
  banner: { js: "// Generated by scripts/build-esm.mjs from src/anywidget_archimate/ui/*.ts: edit those, then npm run build" },
});
const text = result.outputFiles[0].text;

if (process.argv.includes("--check")) {
  let committed = "";
  try {
    committed = readFileSync(out, "utf8").replaceAll("\r\n", "\n");
  } catch {
    // missing: stale
  }
  if (committed !== text) {
    console.error("src/anywidget_archimate/ui/dist/widget.js is stale: run `npm run build` in the package root");
    process.exit(1);
  }
} else {
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, text);
  console.log(`wrote ${out} (${text.length} bytes)`);
}
